const demo = document.getElementById("demo");
const triggers = demo.querySelectorAll(".menu-button[aria-controls]");
let currentLanguage = "zh";
let currentScene = "folder";
let currentDetail = "hintFolder";

function initialLanguage() {
  const requested = new URLSearchParams(location.search).get("lang");
  if (requested === "zh" || requested === "en") return requested;
  let saved;
  try {
    saved = localStorage.getItem("rc-lang");
  } catch (error) {
    saved = null;
  }
  if (saved === "zh" || saved === "en") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function applyLanguage(language) {
  currentLanguage = language;
  const text = COPY[language];
  document.documentElement.lang = language === "zh" ? "zh-Hans" : "en";
  document.title = text.title;
  document.querySelector('meta[name="description"]').content = text.description;
  document.querySelector('meta[property="og:title"]').content = text.title;
  document.querySelector('meta[property="og:description"]').content = text.socialDescription;
  for (const element of document.querySelectorAll("[data-t]")) {
    element.textContent = text[element.dataset.t];
  }
  for (const element of document.querySelectorAll("[data-aria]")) {
    element.setAttribute("aria-label", text[element.dataset.aria]);
  }
  document.querySelector("[data-install]").href = text.installURL;
  updatePreviewText();
  try {
    localStorage.setItem("rc-lang", language);
  } catch (error) {
    return;
  }
}

function updatePreviewText() {
  const text = COPY[currentLanguage];
  document.getElementById("preview-context").textContent = text[currentScene === "folder" ? "contextFolder" : "contextFile"];
  document.getElementById("demo-feedback").textContent = text[currentDetail];
}

function setSubmenu(trigger, open) {
  trigger.setAttribute("aria-expanded", String(open));
  document.getElementById(trigger.getAttribute("aria-controls")).hidden = !open;
}

function closeSubmenus() {
  for (const trigger of triggers) setSubmenu(trigger, false);
}

function setScene(scene) {
  currentScene = scene;
  currentDetail = scene === "folder" ? "hintFolder" : "hintFile";
  closeSubmenus();
  for (const button of demo.querySelectorAll("[data-scene]")) {
    button.setAttribute("aria-pressed", String(button.dataset.scene === scene));
    document.getElementById(button.getAttribute("aria-controls")).hidden = button.dataset.scene !== scene;
  }
  const trigger = document.querySelector(`#${scene}-menu .menu-button[aria-controls]`);
  setSubmenu(trigger, true);
  updatePreviewText();
}

for (const button of demo.querySelectorAll("[data-scene]")) {
  button.addEventListener("click", () => setScene(button.dataset.scene));
}

for (const trigger of triggers) {
  trigger.addEventListener("click", () => {
    const open = trigger.getAttribute("aria-expanded") !== "true";
    closeSubmenus();
    setSubmenu(trigger, open);
  });
}

for (const button of demo.querySelectorAll("[data-detail]")) {
  button.addEventListener("click", () => {
    currentDetail = button.dataset.detail;
    updatePreviewText();
  });
}

document.addEventListener("click", (event) => {
  if (!demo.contains(event.target)) closeSubmenus();
});

demo.addEventListener("keydown", (event) => {
  if (event.key !== "Escape") return;
  const trigger = document.querySelector(`#${currentScene}-menu [aria-expanded="true"]`);
  if (trigger) {
    closeSubmenus();
    trigger.focus();
  }
});

document.getElementById("lang-switch").addEventListener("click", () => {
  applyLanguage(currentLanguage === "zh" ? "en" : "zh");
});

async function loadRelease() {
  try {
    const response = await fetch("https://api.github.com/repos/hy-shine/rightclick/releases/latest", { signal: AbortSignal.timeout(6000) });
    if (!response.ok) return;
    const release = await response.json();
    const version = /(\d+\.\d+\.\d+)/.exec(release.tag_name ?? release.name ?? "");
    if (version) document.getElementById("release-version").textContent = ` · v${version[1]}`;
    for (const link of document.querySelectorAll("[data-arch]")) {
      const asset = (release.assets ?? []).find((item) => item.name.endsWith(`-${link.dataset.arch}.dmg`));
      if (asset) link.href = asset.browser_download_url;
    }
  } catch (error) {
    return;
  }
}

applyLanguage(initialLanguage());
void loadRelease();
